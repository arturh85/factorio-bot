    /// The cost is derived from the recipe table, not typed: a stone furnace
    /// is five stone, a burner drill is three gears, three plates and a
    /// furnace.
    #[test]
    fn cost_is_expanded_through_recipes() {
        let one = scored(&ore_to_plate(1, 1, false));
        // 1 drill (3 gear = 6 plate, +3 plate, + furnace 5 stone),
        // 1 furnace (5 stone), 1 burner inserter (1 plate + 1 gear = 3 plate),
        // belts: 2 + 1 + (3*1+6 = 9) = 12 belts -> 6 crafts of (1 plate + 1 gear) = 18 plate
        let stone = one.cost.get("stone").copied().unwrap_or_default();
        assert!((stone - 10.).abs() < 1e-9, "stone {stone}");
        // ... plus the output side: one more burner inserter (3) and an
        // iron chest (8).
        let iron = one.iron_cost();
        assert!(
            (iron - (9. + 3. + 18. + 3. + 8.)).abs() < 1e-9,
            "iron {iron}"
        );
    }

    /// Ranking puts reached candidates ahead of unreached ones and the
    /// higher rate first; ties break on the cheaper block.
    #[test]
    fn rank_prefers_reached_then_rate_then_cost() {
        let a = scored(&ore_to_plate(1, 2, true));
        let b = scored(&ore_to_plate(3, 2, true));
        let c = scored(&ore_to_plate(3, 3, true));
        let order: Vec<String> = rank(vec![a, c.clone(), b.clone()])
            .into_iter()
            .map(|f| f.name)
            .collect();
        // 3x2 and 3x3 both make 45 ore/min into >= 37.5 of furnace: 3x3 makes
        // 45, 3x2 makes 37.5, 1x2 makes 15.
        assert_eq!(order, vec!["gen-3x3", "gen-3x2", "gen-1x2"]);
        assert!(c.plates_per_min() > b.plates_per_min());
    }
