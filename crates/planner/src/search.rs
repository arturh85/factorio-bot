//! A search that ranks candidate layouts by the flow they would sustain.
//!
//! # What this optimises, and what it does not
//!
//! The owner's question was *"we have so many goals and decisions ... maybe
//! genetic algorithms or some other stuff could optimize the plan at the end
//! ... or we make simulations, trying which layout / prio maximizes achieved
//! flow rate"*. The objective behind it is a base that **compounds** -- every
//! science pack automated, the base upgraded continuously -- not a completion
//! time. The quantity that compounds is a production *rate*, so that is what
//! the fitness here is: items per minute a layout would sustain, as
//! [`FlowGraph::sustained_production_rates`] predicts it, beside what the
//! layout costs in plates to stand up, so a rate can be read per plate
//! invested.
//!
//! **The search space is deliberately small and deliberately real.** A
//! candidate is a [`Layout`]: either a decoded blueprint fixture or a block
//! generated by [`ore_to_plate`] in the exact geometry of the fixture
//! `OreToPlateThree` from `scripts/rcontest.lua`, which has a live
//! measurement (36.2 plates/min, `docs/superpowers/notes/
//! 2026-09-07-the-block-was-drill-limited.md`). Generating in the measured
//! geometry is what makes the model's number checkable: `gen-3x2` **is** that
//! fixture, entity for entity (`generated_three_by_two_is_the_measured_fixture`
//! asserts it), so its predicted rate has a game number to stand beside.
//!
//! # Why enumeration and not a genetic algorithm
//!
//! One candidate costs a fresh [`EntityGraph`] holding the ore patch plus the
//! block, one `connect`, and one whole-base balance -- **milliseconds**, as
//! the `search` CLI measures and prints beside every row. The parametric
//! family is `drills x furnaces` and a whole 8x8 sweep is 64 evaluations,
//! under a second. A population-based search over a space this size would be
//! ranking noise against exhaustive truth; the owner's suggestion is kept in
//! mind for the day the space is combinatorial (siting, orientation, belt
//! topology), and is not warranted by the cost measured today.
//!
//! # What the ranking cannot see, stated up front
//!
//! Every limit of the flow graph is a limit here, and three of them decide
//! whether a ranking can be *trusted* rather than merely produced:
//!
//! - **A block nothing mines into reads as zero, not as slow.** The walk in
//!   [`FlowGraph::update`] roots only at a drill standing on ore or an
//!   offshore pump. A chest-fed or hand-fed smelter -- `TJunctionSmelter`,
//!   `FurnaceLine`, `SmeltRow24` -- has no incoming edge and scores 0. That
//!   is not a prediction the game will make, so those fixtures are reported
//!   with `reached = false` and excluded from the ranking rather than sorted
//!   to the bottom as if they were bad.
//! - **Fuel is invisible.** A burner's coal is not a recipe ingredient
//!   (`the_ground_is_not_a_recipe`), so a block whose coal branch is deleted
//!   scores identically to the same block with it. In the game the burner
//!   inserters stop when their hand charge burns out and the block makes
//!   nothing. [`ore_to_plate`] takes `coal: false` to build exactly that
//!   control; the CLI prints it beside its twin so the tie is visible.
//! - **A multi-output machine is scored per product**, one
//!   `ProductionLine` each with an independent outlet cap. The game stops
//!   the whole machine when any one output backs up. A layout that leaves
//!   one refinery product undrained is therefore scored at nameplate on the
//!   others when the true steady state is zero -- a search over oil layouts
//!   would exploit this immediately, and this module refuses to run one:
//!   [`Layout::multi_output_machines`] names the machines and the CLI marks
//!   the row `unscoreable` rather than ranking it.
//!
//! What the model *does* see is the constraint the measured fixtures were
//! built to probe: whether the drills or the furnaces bind. The 2x2 block
//! measured 28.7/min against 30.0 of drill supply, the 3x2 block 36.2 against
//! 37.5 of furnace capacity, and the balance reproduces both constraints
//! from prototypes. The `search` CLI prints `model / measured` for every
//! candidate handed a live number, which is how the bias is quantified rather
//! than assumed.

