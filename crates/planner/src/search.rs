    fn square_patch(name: &str, half: i32) -> OrePatch {
        let mut tiles = BTreeSet::new();
        for y in -half..half {
            for x in -half..half {
                tiles.insert(Pos(x, y));
            }
        }
        OrePatch {
            resource: name.to_owned(),
            tiles,
        }
    }

